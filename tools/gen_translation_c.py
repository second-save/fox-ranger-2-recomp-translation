#!/usr/bin/env python3
"""gen_translation_c.py - translations/cutscenes_kr.json -> src/fr2_translation_gen.c

The runtime applies the translation in memory when a program is loaded
(fr2_run.c): each entry names a far pointer in the program image (ptr_img)
that must still hold its original value seg:off; it is redirected to the
English string.  The executables themselves are never modified.
Run tools/validate_translation.py against pristine executables first.
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
items = json.load(open(os.path.join(ROOT, 'translations/cutscenes_kr.json'), encoding='utf-8'))
out = ['/* fr2_translation_gen.c - GENERATED by tools/gen_translation_c.py; do not edit. */',
       '#include "fr2_translation.h"', '', 'const Fr2Text g_fr2_texts[] = {']
for x in items:
    en = x['english'].strip()
    try:
        en.encode('ascii')
    except UnicodeEncodeError:
        sys.exit(f"{x['id']}: non-ASCII English text {en!r} (the game font only has ASCII)")
    if len(en) > 36:
        sys.exit(f"{x['id']}: {len(en)} characters, the dialogue box holds 36")
    lit = en.replace('\\', '\\\\').replace('"', '\\"')
    out.append(f'    {{ "{x["module"].lower()}", 0x{int(x["ptr_img"], 16):05X}, 0x{int(x["seg"], 16):04X}, '
               f'0x{int(x["off"], 16):04X}, "{lit}" }},  /* {x["id"]} */')
out += ['    { 0 }', '};', '']
open(os.path.join(ROOT, 'src/fr2_translation_gen.c'), 'w').write('\n'.join(out))
print(f'{len(items)} strings')
