#!/usr/bin/env python3
"""fr2_dispatch_gen.py - extract FR2.EXE's route table into C.

FR2.EXE (small model, 16 KB) is the hub every module execl()s back into with
`fr2.exe <snd> <voice> <ROUTE> [s]`.  Its main() switches on ROUTE ('A'-'Z',
jump table at image 0x580) and execl()s the next module.  Stage routes check
argv[4][0]=='s' first (save/start variant).  Only the first execl of each path
matters (the others are fall-through after a failed exec).

Writes src/fr2_dispatch_gen.c.
"""
import os, struct, capstone
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'work/FR2_UNP.EXE'), 'rb').read()
h = struct.unpack('<H', d[8:10])[0] * 16
img = d[h:]
DG = 0x02A8 * 16
EXECL = 0x27AE
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_16)


def cstr(off):
    e = img.index(b'\0', DG + off)
    return img[DG + off:e].decode('latin1')


def first_execl(addr):
    """args of the first execl reached by straight-line code from addr."""
    stack, ax, mode13 = [], None, False
    for ins in md.disasm(img[addr:addr + 200], addr):
        m, op = ins.mnemonic, ins.op_str
        if m == 'mov' and op.startswith('ax, 0x') or op == 'ax, 0':
            ax = int(op.split(', ')[1], 16)
        elif m == 'push' and op == 'ax':
            stack.append(cstr(ax) if ax else None)
        elif m == 'push' and op == 'word ptr [si + 8]':
            stack.append('$4')                      # pass through argv[4]
        elif m == 'call' and int(op, 16) == 0x05BD:     # set video mode 13h
            mode13 = True
        elif m == 'call':
            assert int(op, 16) == EXECL, hex(ins.address)
            args = list(reversed(stack))
            assert args[-1] is None
            return (['@13'] if mode13 else []) + args[:-1]
        elif m == 'jmp':
            return first_execl(int(op, 16))
    raise SystemExit(f'no execl from {addr:#x}')


def case(addr):
    """returns (normal_args, s_args or None)."""
    ins = list(md.disasm(img[addr:addr + 16], addr))
    if ins[0].mnemonic == 'mov' and ins[0].op_str == 'al, byte ptr [bp - 0xe]':
        je = next(i for i in ins if i.mnemonic == 'je')
        jmp = next(i for i in ins if i.mnemonic == 'jmp')
        return first_execl(int(jmp.op_str, 16)), first_execl(int(je.op_str, 16))
    return first_execl(addr), None


tbl = struct.unpack_from('<26H', img, 0x580)
out = ['/* fr2_dispatch_gen.c - GENERATED by tools/fr2_dispatch_gen.py from FR2.EXE; do not edit. */',
       '#include "fr2_modules.h"', '', 'const Fr2Route g_fr2_routes[26] = {']
def lit(a):
    return '"%s"' % a
for i, t in enumerate(tbl):
    n, s = case(t)
    def arr(v):
        if v is None:
            return 'NULL'
        return '(const char *const[]){ ' + ', '.join(lit(x) for x in v) + ', NULL }'
    out.append(f"    /* {chr(65 + i)} */ {{ {arr(n)}, {arr(s)} }},  /* '@13' = set mode 13h first, '$4' = argv[4] */")
    print(chr(65 + i), n, s)
out.append('};')
open(os.path.join(ROOT, 'src/fr2_dispatch_gen.c'), 'w').write('\n'.join(out) + '\n')
